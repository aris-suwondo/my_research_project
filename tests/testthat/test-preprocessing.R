# 1. LOAD TESTING PACKAGE ----

library(testthat)


# 2. TEST PREPROCESSING ----

test_that("Preprocessing produces the expected cleaned dataset", {

  # testthat runs tests from the test directory.
  # Move temporarily to the project root so our scripts can find their files.
  project_root <- normalizePath("../..", mustWork = TRUE)

  withr::with_dir(project_root, {

    # Run the original import and preprocessing modules.
    source("code/01_data_import.R", local = TRUE)
    source("code/02_preprocessing.R", local = TRUE)

    # Read the datasets generated by the modules.
    raw_data <- read.csv("data/raw/penguins_raw.csv")

    cleaned_data <- read.csv(
      "data/processed/cleaned_penguins_modular.csv"
    )

    # 3. CHECK OBSERVATION COUNTS ----

    expect_equal(nrow(raw_data), 344L)

    expect_equal(nrow(cleaned_data), 342L)

    # 4. CHECK MISSING VALUES ----

    # Neither regression variable should contain missing values.
    expect_false(anyNA(cleaned_data$bill_length_mm))

    expect_false(anyNA(cleaned_data$body_mass_g))

    # 5. CHECK THE PREPROCESSING RESULT ----

    # Independently calculate which rows should remain.
    expected_data <- raw_data[
      !is.na(raw_data$bill_length_mm) &
        !is.na(raw_data$body_mass_g),
      ,
      drop = FALSE
    ]

    # Reset row names so both datasets can be compared.
    rownames(expected_data) <- NULL

    # Check that the complete cleaned dataset matches our expectation.
    expect_equal(cleaned_data, expected_data)

  })
})